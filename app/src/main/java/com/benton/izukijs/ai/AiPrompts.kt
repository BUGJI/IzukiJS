        例如：<<TOOL>>{"name":"click","arguments":{"x":540,"y":1200}}
        每次只输出一个工具调用，等待框架返回「工具结果」后再继续。
        不需要操作设备时，正常用中文输出总结，不要包含 <<TOOL>> 标记。
    """.trimIndent()

